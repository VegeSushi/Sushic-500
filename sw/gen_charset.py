assert len(FONT_8X12) == 64 * 12

def main():
    out_dir = "build"
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "charset.hex")

    lines = []
    for chr7 in range(128):          # dd[6:0] is 7 bits -> 128 possible codes
        base = chr7 & 0x3F            # real hardware only decodes 6 bits
        for row in range(16):         # row_v[3:0] is 4 bits -> 16 slots/char
            if row < 12:
                lines.append(FONT_8X12[base * 12 + row])
            else:
                lines.append(0x00)    # unused rows, padding

    assert len(lines) == 128 * 16

    with open(out_path, "w") as f:
        for b in lines:
            f.write("%02X\n" % b)

    print(f"wrote {len(lines)} bytes to {out_path}")

if __name__ == "__main__":
    main()